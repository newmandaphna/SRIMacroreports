"""Phase A profiler -- DISCOVER, DO NOT ASSUME.

Profiles whatever real exports are present in data/raw/ and rewrites the Part 1
"Observed inventory" of docs/data-dictionary.md with facts: per file, row count,
column names + inferred dtypes, detected date column(s) with observed min/max,
and inferred grain. **Only aggregates are emitted -- never a cell value** (the
PHI rule; the file is committed and public).

If data/raw/ is empty or lacks prior-year coverage for the target period, the
profiler does NOT fabricate data: it leaves docs/export-request.md as the
instruction to pull real exports and reports exactly what is short.

Determinism: files are processed in sorted order, columns in header order, and
no wall-clock or randomness enters the analysis path (ASSUMPTIONS §16).
"""
